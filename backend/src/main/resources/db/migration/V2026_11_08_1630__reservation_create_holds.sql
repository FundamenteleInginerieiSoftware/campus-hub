-- Reservation Holds: temporary 1-minute slot locking for fair booking and concurrency protection
CREATE TABLE reservation_holds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id BIGINT NOT NULL REFERENCES assets(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    start_time TIMESTAMP NOT NULL,
    end_time TIMESTAMP NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);

-- Fast lookup for active slot holds on an asset (concurrency & availability checks)
CREATE INDEX idx_reservation_holds_asset_slot
    ON reservation_holds (asset_id, status, expires_at, start_time, end_time);

-- Fast lookup for student active hold quotas
CREATE INDEX idx_reservation_holds_user_active
    ON reservation_holds (user_id, status, expires_at);

-- Fast sweep index for scheduled background cleanup of expired holds
CREATE INDEX idx_reservation_holds_expiry_sweep
    ON reservation_holds (status, expires_at);
