-- Migration to support student reservation transfers with state tracking
CREATE TABLE reservation_transfers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL REFERENCES reservations(id) ON DELETE CASCADE,
    from_user_id BIGINT NOT NULL,
    to_user_id BIGINT NOT NULL,
    status VARCHAR(32) NOT NULL,
    requested_at TIMESTAMP NOT NULL,
    responded_at TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE INDEX idx_reservation_transfers_reservation_id ON reservation_transfers(reservation_id);
CREATE INDEX idx_reservation_transfers_to_user_id ON reservation_transfers(to_user_id, status);
