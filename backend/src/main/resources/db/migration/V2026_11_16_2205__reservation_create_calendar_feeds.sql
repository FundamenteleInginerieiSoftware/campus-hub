-- Private iCalendar feed links (one SHA-256 token hash per user).
-- user_id is UNIQUE so each user owns at most one active feed link (regenerating replaces the hash in the same row).
-- token_hash is UNIQUE so public calendar lookups resolve via a single indexed lookup with no collisions.
CREATE TABLE calendar_feeds (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL UNIQUE REFERENCES users (id),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMP   NOT NULL
);
