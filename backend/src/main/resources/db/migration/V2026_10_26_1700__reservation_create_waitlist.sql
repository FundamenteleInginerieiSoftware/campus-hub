CREATE TABLE waitlist_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    asset_id BIGINT NOT NULL REFERENCES assets(id),
    start_time TIMESTAMP NOT NULL,
    end_time TIMESTAMP NOT NULL,
    status VARCHAR(32) NOT NULL,
    promoted_reservation_id BIGINT REFERENCES reservations(id),
    created_at TIMESTAMP NOT NULL,
    resolved_at TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE INDEX idx_waitlist_asset_status_created ON waitlist_entries(asset_id, status, created_at);
CREATE INDEX idx_waitlist_user_status ON waitlist_entries(user_id, status);
