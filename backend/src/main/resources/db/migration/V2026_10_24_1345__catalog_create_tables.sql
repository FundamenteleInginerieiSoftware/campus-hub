-- Catalog tables: categories, lab_rooms, assets.
-- Owned by Liviu Nedelcu (@NliviuN).

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(500)
);

CREATE UNIQUE INDEX uq_categories_name_lower ON categories (LOWER(name));

CREATE TABLE lab_rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    building VARCHAR(100)
);

CREATE UNIQUE INDEX uq_lab_rooms_code_lower ON lab_rooms (LOWER(code));

CREATE TABLE assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    model VARCHAR(150) NOT NULL,
    serial_number VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,
    status VARCHAR(32) NOT NULL,
    category_id BIGINT NOT NULL REFERENCES categories (id),
    lab_room_id BIGINT NOT NULL REFERENCES lab_rooms (id),
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

CREATE UNIQUE INDEX uq_assets_serial_number_lower ON assets (LOWER(serial_number));
CREATE INDEX idx_assets_category_id ON assets (category_id);
CREATE INDEX idx_assets_lab_room_id ON assets (lab_room_id);
CREATE INDEX idx_assets_status ON assets (status);
CREATE INDEX idx_assets_model ON assets (model);
