-- Everyone who can log in. reservations, incident_reports and others point here with a user_id
-- foreign key, so this table must exist before theirs (their migrations need a later timestamp).
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Stored in lowercase (the User constructor does it), so this plain UNIQUE also blocks
    -- "Ana@campus.test" next to "ana@campus.test".
    email         VARCHAR(255) NOT NULL UNIQUE,
    -- BCrypt hash with its "{bcrypt}" prefix, never the plain password.
    password_hash VARCHAR(255) NOT NULL,
    full_name     VARCHAR(100) NOT NULL,
    -- STUDENT or ADMIN, saved as text so adding a role later can't shift the meaning of old rows.
    role          VARCHAR(32)  NOT NULL,
    -- false = blocked by an admin; login refuses the account but its bookings and reports stay.
    enabled       BOOLEAN      NOT NULL,
    created_at    TIMESTAMP    NOT NULL
);
