package com.campus.incident.service;

import static org.assertj.core.api.Assertions.assertThat;

import com.campus.common.error.BusinessRuleException;
import com.campus.incident.domain.IncidentReport.IncidentSeverity;
import com.campus.incident.web.CreateIncidentRequest;
import java.util.List;
import java.util.UUID;
import java.util.concurrent.CopyOnWriteArrayList;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.Future;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.atomic.AtomicInteger;
import java.util.function.LongConsumer;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;

/**
 * #229 review (Matei): the limit of 3 OPEN reports per student must hold when one student sends two reports at
 * the same moment. Built like Calin's ReservationConcurrencyIT (#97, #173).
 *
 * <p>Not @Transactional on purpose: each thread runs reportIncident in its own transaction and must really
 * commit, or the other thread could never see its report. So the data is inserted with plain SQL here and
 * deleted again in tearDown.
 *
 * <p>Every id is generated by the database ({@code RETURNING id}) and every unique value carries a random tag
 * (#346), so the test never collides with rows other tests or an earlier, interrupted run left in campus_test.
 */
@SpringBootTest
class IncidentQuotaConcurrencyIT {

    @Autowired
    private IncidentService incidentService;

    @Autowired
    private JdbcTemplate jdbcTemplate;

    private Long studentId;
    private Long categoryId;
    private Long labRoomId;
    private Long assetA;
    private Long assetB;
    // The two reports the student already has sit on a third asset, so A and B start AVAILABLE.
    private Long assetWithOldReports;

    @BeforeEach
    void setUp() {
        String tag = UUID.randomUUID().toString().substring(0, 8);
        studentId = jdbcTemplate.queryForObject("""
                INSERT INTO users (email, password_hash, full_name, role, enabled, created_at)
                VALUES (?, '{bcrypt}hash', 'Incident quota student', 'STUDENT', true, NOW())
                RETURNING id
                """, Long.class, "student-" + tag + "@incquota.test");
        categoryId = jdbcTemplate.queryForObject(
                "INSERT INTO categories (name) VALUES (?) RETURNING id", Long.class, "Incident quota " + tag);
        labRoomId = jdbcTemplate.queryForObject(
                "INSERT INTO lab_rooms (code, name) VALUES (?, ?) RETURNING id",
                Long.class,
                "LAB-QUOTA-" + tag,
                "Incident quota lab " + tag);
        assetA = insertAvailableAsset("Quota scope A", "SN-QUOTA-A-" + tag);
        assetB = insertAvailableAsset("Quota scope B", "SN-QUOTA-B-" + tag);
        assetWithOldReports = insertAvailableAsset("Quota scope C", "SN-QUOTA-C-" + tag);
        // The student already has 2 OPEN reports: one more is allowed, two more are not.
        jdbcTemplate.update("""
                INSERT INTO incident_reports (asset_id, reported_by_id, description, severity, status, created_at)
                VALUES (?, ?, 'Old report 1', 'LOW', 'OPEN', NOW()),
                       (?, ?, 'Old report 2', 'LOW', 'OPEN', NOW())
                """, assetWithOldReports, studentId, assetWithOldReports, studentId);
    }

    @AfterEach
    void tearDown() {
        jdbcTemplate.update("DELETE FROM incident_reports WHERE reported_by_id = ?", studentId);
        jdbcTemplate.update("DELETE FROM audit_logs WHERE actor_id = ?", studentId);
        jdbcTemplate.update("DELETE FROM assets WHERE id IN (?, ?, ?)", assetA, assetB, assetWithOldReports);
        jdbcTemplate.update("DELETE FROM lab_rooms WHERE id = ?", labRoomId);
        jdbcTemplate.update("DELETE FROM categories WHERE id = ?", categoryId);
        jdbcTemplate.update("DELETE FROM users WHERE id = ?", studentId);
    }

    @Test
    @DisplayName("Quota lock: a student with 2 OPEN reports sends 2 HIGH reports at once, exactly 1 is saved")
    void twoParallelReportsFromOneStudent_cannotBothPassTheLimit() throws Exception {
        ExecutorService executor = Executors.newFixedThreadPool(2);
        CountDownLatch ready = new CountDownLatch(2);
        CountDownLatch go = new CountDownLatch(1);
        AtomicInteger saved = new AtomicInteger();
        AtomicInteger refused = new AtomicInteger();
        List<Throwable> unexpected = new CopyOnWriteArrayList<>();

        // Both threads wait at the gate, then report at the same moment on two different assets. Different
        // assets lock different rows, so only the per-student quota lock can make them wait for each other.
        LongConsumer reportOn = assetId -> {
            ready.countDown();
            try {
                go.await();
                incidentService.reportIncident(
                        new CreateIncidentRequest(assetId, "Does not turn on", IncidentSeverity.HIGH),
                        studentId,
                        false);
                saved.incrementAndGet();
            } catch (BusinessRuleException ex) {
                if ("TOO_MANY_OPEN_INCIDENTS".equals(ex.getCode())) {
                    refused.incrementAndGet();
                } else {
                    unexpected.add(ex);
                }
            } catch (Throwable t) {
                unexpected.add(t);
            }
        };

        // shutdownNow() in finally so a timeout does not leave the threads running; awaitTermination so an
        // interrupted thread is done before tearDown deletes its rows.
        try {
            Future<?> first = executor.submit(() -> reportOn.accept(assetA));
            Future<?> second = executor.submit(() -> reportOn.accept(assetB));
            assertThat(ready.await(5, TimeUnit.SECONDS))
                    .as("both threads reached the start gate")
                    .isTrue();
            go.countDown();
            first.get(10, TimeUnit.SECONDS);
            second.get(10, TimeUnit.SECONDS);
        } finally {
            executor.shutdownNow();
            executor.awaitTermination(5, TimeUnit.SECONDS);
        }

        assertThat(unexpected).as("no other error than the limit").isEmpty();
        assertThat(saved.get())
                .as("limit: 2 OPEN + 2 parallel reports, only 1 may pass; "
                        + "see IncidentService.reportIncident (lockReporterQuota before the count)")
                .isEqualTo(1);
        assertThat(refused.get())
                .as("the other report gets 409 TOO_MANY_OPEN_INCIDENTS")
                .isEqualTo(1);
        assertThat(jdbcTemplate.queryForObject(
                        "SELECT count(*) FROM incident_reports WHERE reported_by_id = ? AND status = 'OPEN'",
                        Long.class,
                        studentId))
                .as("the student ends with exactly 3 OPEN reports in the database, never 4")
                .isEqualTo(3L);
        assertThat(jdbcTemplate.queryForObject(
                        "SELECT count(*) FROM assets WHERE id IN (?, ?) AND status = 'UNDER_MAINTENANCE'",
                        Long.class,
                        assetA,
                        assetB))
                .as("only the asset of the saved report is out of use; the refused one rolled back")
                .isEqualTo(1L);
    }

    private Long insertAvailableAsset(String name, String serialNumber) {
        return jdbcTemplate.queryForObject("""
                INSERT INTO assets (name, model, serial_number, status, category_id, lab_room_id, created_at, updated_at)
                VALUES (?, 'QUOTA-MODEL', ?, 'AVAILABLE', ?, ?, NOW(), NOW())
                RETURNING id
                """, Long.class, name, serialNumber, categoryId, labRoomId);
    }
}
